"""crisis SQLAlchemy models: CrisisEvent, CrisisAlert (ERD section 2.7).

Additions to the ERD, for delivery tracking and offline safety:
  crisis_events.location_source           device fix, home fallback, or none
  crisis_alerts.phone / recipient_name    snapshot at send time, so later edits don't
                                          change who an old alert went to
  crisis_alerts.provider_ref, last_error  delivery tracking and retries
  crisis_alerts.created_at, updated_at    used by the retry sweep
CrisisAlert.caregiver_id (assigned caregiver, CR-1) arrives with bookings.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from enum import StrEnum
from typing import Any

from geoalchemy2 import Geography, Geometry
from sqlalchemy import (
    CheckConstraint,
    Enum,
    ForeignKey,
    Index,
    Integer,
    SmallInteger,
    String,
    cast,
    func,
    text,
)
from sqlalchemy.orm import Mapped, column_property, mapped_column, relationship

from app.database import Base, CreatedAtMixin, TimestampMixin, UUIDPrimaryKeyMixin
from app.domains.patients.models import AlertChannel


def _enum_values(enum_cls: type[StrEnum]) -> list[str]:
    return [member.value for member in enum_cls]


class CrisisStatus(StrEnum):
    ACTIVE = "active"
    RESOLVED = "resolved"
    CANCELLED = "cancelled"  # false alarm


class LocationSource(StrEnum):
    DEVICE = "device"  # live GPS fix sent with the button press
    HOME = "home"  # no fix; fell back to the patient's home location
    NONE = "none"  # no fix and no home location on record


class AlertStatus(StrEnum):
    QUEUED = "queued"
    SENT = "sent"
    DELIVERED = "delivered"  # set once provider delivery reports are wired in
    FAILED = "failed"
    SKIPPED = "skipped"  # the crisis was closed before this alert went out


class CrisisEvent(UUIDPrimaryKeyMixin, CreatedAtMixin, Base):
    __tablename__ = "crisis_events"
    __table_args__ = (
        # Fast "is there already an active crisis for this patient?" lookup.
        Index(
            "ix_crisis_events_patient_active",
            "patient_id",
            "triggered_at",
            postgresql_where=text("status = 'active'"),
        ),
    )

    patient_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("patients.id", ondelete="RESTRICT"), index=True
    )
    triggered_by: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL")
    )
    # Generated by the app when the button is pressed; makes offline replays safe.
    client_event_id: Mapped[uuid.UUID] = mapped_column(unique=True)
    location: Mapped[Any | None] = mapped_column(
        Geography(geometry_type="POINT", srid=4326, spatial_index=False)
    )
    location_source: Mapped[LocationSource] = mapped_column(
        Enum(LocationSource, name="crisis_location_source", values_callable=_enum_values)
    )
    accuracy_m: Mapped[int | None] = mapped_column(Integer)
    location_captured_at: Mapped[datetime | None]  # when the device got the GPS fix
    status: Mapped[CrisisStatus] = mapped_column(
        Enum(CrisisStatus, name="crisis_status", values_callable=_enum_values),
        default=CrisisStatus.ACTIVE,
        server_default=CrisisStatus.ACTIVE.value,
    )
    triggered_at: Mapped[datetime]  # when the button was pressed (device time, validated)
    resolved_at: Mapped[datetime | None]
    resolved_by: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL")
    )
    outcome_facility_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("facilities.id", ondelete="SET NULL"), index=True
    )

    alerts: Mapped[list[CrisisAlert]] = relationship(
        back_populates="crisis_event", lazy="raise", order_by="CrisisAlert.created_at"
    )

    latitude: Mapped[float | None] = column_property(func.ST_Y(cast(location, Geometry)))
    longitude: Mapped[float | None] = column_property(func.ST_X(cast(location, Geometry)))


class CrisisAlert(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """One alert to one recipient, so each delivery is retried and tracked on its own."""

    __tablename__ = "crisis_alerts"
    __table_args__ = (
        CheckConstraint(
            "num_nonnulls(guardian_id, emergency_contact_id) = 1", name="exactly_one_recipient"
        ),
        # The retry sweep scans only alerts that still need sending.
        Index(
            "ix_crisis_alerts_pending",
            "created_at",
            postgresql_where=text("status IN ('queued', 'failed')"),
        ),
    )

    crisis_event_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("crisis_events.id", ondelete="CASCADE"), index=True
    )
    guardian_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("guardians.id", ondelete="SET NULL")
    )
    emergency_contact_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("emergency_contacts.id", ondelete="SET NULL")
    )
    recipient_name: Mapped[str] = mapped_column(String(200))
    phone: Mapped[str] = mapped_column(String(20))
    # Reuses the alert_channel enum type created with emergency_contacts.
    channel: Mapped[AlertChannel] = mapped_column(
        Enum(AlertChannel, name="alert_channel", values_callable=_enum_values),
        default=AlertChannel.SMS,
        server_default=AlertChannel.SMS.value,
    )
    status: Mapped[AlertStatus] = mapped_column(
        Enum(AlertStatus, name="crisis_alert_status", values_callable=_enum_values),
        default=AlertStatus.QUEUED,
        server_default=AlertStatus.QUEUED.value,
    )
    attempts: Mapped[int] = mapped_column(SmallInteger, default=0, server_default=text("0"))
    sent_at: Mapped[datetime | None]
    provider_ref: Mapped[str | None] = mapped_column(String(128))
    last_error: Mapped[str | None] = mapped_column(String(300))

    crisis_event: Mapped[CrisisEvent] = relationship(back_populates="alerts", lazy="raise")

    @property
    def recipient_type(self) -> str:
        return "guardian" if self.guardian_id else "emergency_contact"
