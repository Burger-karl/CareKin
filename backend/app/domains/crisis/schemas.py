"""crisis request and response schemas (kickoff 2.6).

Every response carries `disclaimer` and `emergency_number` (PRD CR-3). Nothing in
this domain gives treatment advice: it routes people to contacts and facilities.
"""

import uuid
from datetime import datetime
from typing import Annotated

from pydantic import (
    AwareDatetime,
    BaseModel,
    ConfigDict,
    Field,
    StringConstraints,
    model_validator,
)

from app.config import get_settings
from app.domains.crisis.models import AlertStatus, CrisisStatus, LocationSource
from app.domains.patients.models import AlertChannel


def disclaimer() -> str:
    number = get_settings().EMERGENCY_NUMBER
    return (
        "CareKin does not give medical advice and does not replace emergency care. "
        f"If you are in danger or very unwell, go to the nearest hospital or call {number}."
    )


class SafetyNotice(BaseModel):
    disclaimer: str = Field(default_factory=disclaimer)
    emergency_number: str = Field(default_factory=lambda: get_settings().EMERGENCY_NUMBER)


# ---------------------------------------------------------------- requests
class LocationIn(BaseModel):
    latitude: float = Field(ge=-90, le=90)
    longitude: float = Field(ge=-180, le=180)
    accuracy_m: int | None = Field(default=None, ge=0, le=100_000)
    captured_at: AwareDatetime | None = Field(
        default=None, description="When the device got this GPS fix. Used to flag stale fixes."
    )


class CrisisTriggerIn(BaseModel):
    model_config = ConfigDict(extra="forbid")

    patient_id: uuid.UUID
    client_event_id: uuid.UUID = Field(
        description="Generated by the app when the button is pressed. Resending the same id "
        "(e.g. after being offline) returns the original event instead of a new one."
    )
    location: LocationIn | None = Field(
        default=None, description="Omit if there's no GPS fix; the alert still goes out."
    )
    triggered_at: AwareDatetime | None = Field(
        default=None,
        description="When the button was pressed, if it was queued offline. "
        "Ignored if it's in the future or more than 24 hours old.",
    )


class CrisisResolveIn(BaseModel):
    model_config = ConfigDict(extra="forbid")

    false_alarm: bool = Field(default=False, description="Pressed by mistake: marks it cancelled.")
    outcome_facility_id: uuid.UUID | None = Field(
        default=None, description="Where the patient went, if anywhere."
    )
    add_to_passport: bool = Field(
        default=False,
        description="Record this crisis in the health passport. Needs health-data consent.",
    )
    note: str | None = Field(
        default=None, max_length=500, description="Patient's own note for the passport entry."
    )

    @model_validator(mode="after")
    def _false_alarm_has_no_outcome(self) -> "CrisisResolveIn":
        if self.false_alarm and (self.add_to_passport or self.outcome_facility_id):
            raise ValueError("A false alarm can't have an outcome facility or a passport entry")
        return self


class CrisisAlertRetryIn(BaseModel):
    model_config = ConfigDict(extra="forbid")

    crisis_event_id: uuid.UUID


# ---------------------------------------------------------------- responses
class LocationOut(BaseModel):
    source: LocationSource
    latitude: float | None = None
    longitude: float | None = None
    accuracy_m: int | None = None
    captured_at: datetime | None = None
    stale: bool = Field(description="The GPS fix was old when the button was pressed.")


class AlertOut(BaseModel):
    id: uuid.UUID
    recipient_type: str  # guardian | emergency_contact
    recipient_name: str
    phone: str = Field(description="Masked, e.g. +234*****5678")
    channel: AlertChannel
    status: AlertStatus
    attempts: int
    sent_at: datetime | None


class FacilityOut(BaseModel):
    id: uuid.UUID
    name: str
    facility_type: str | None = Field(default=None, examples=["teaching_hospital"])
    address: str
    latitude: float
    longitude: float
    distance_m: int = Field(description="Straight-line distance; road distance comes with OSRM.")
    call_number: str | None = Field(description="Emergency line if listed, else main line.")
    phone: str | None
    emergency_phone: str | None
    crisis_services: list[str] = Field(examples=[["emergency_24h", "haematologist"]])
    verification_status: str = Field(examples=["verified"])
    last_verified_at: datetime | None
    directions_url: str


class FacilitiesOut(SafetyNotice):
    crisis_event_id: uuid.UUID
    location_source: LocationSource
    radius_km: float | None
    widened_search: bool = Field(
        description="Nothing verified was inside the normal radius, so a wider area was searched."
    )
    facilities_available: bool = Field(
        description="False until the facility directory is live: show the emergency number "
        "instead of 'no facilities nearby'."
    )
    facilities: list[FacilityOut]


class CrisisEventOut(SafetyNotice):
    id: uuid.UUID
    patient_id: uuid.UUID
    client_event_id: uuid.UUID
    status: CrisisStatus
    triggered_at: datetime
    resolved_at: datetime | None
    outcome_facility_id: uuid.UUID | None
    location: LocationOut
    alerts: list[AlertOut]
    no_contacts: bool = Field(
        description="Nobody could be alerted. The app should prompt the user to call "
        "the emergency number and add contacts."
    )


class CrisisTriggerOut(CrisisEventOut):
    """Includes nearby facilities so the app needs no second request to show them."""

    nearby: FacilitiesOut


class CrisisResolveOut(CrisisEventOut):
    passport_entry_id: uuid.UUID | None


class CrisisAlertRetryOut(SafetyNotice):
    crisis_event_id: uuid.UUID
    alerts: list[AlertOut]
    new_recipients: int = Field(description="Contacts added since the crisis started, now queued.")
    queued: int = Field(description="Alerts that will be (re)sent now.")


# ---------------------------------------------------------------- device keys
class DeviceKeyCreateIn(BaseModel):
    model_config = ConfigDict(extra="forbid")

    patient_id: uuid.UUID
    label: Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=80)] = (
        Field(description="Shown in settings, e.g. 'Chrome on Android'.")
    )


class DeviceKeyOut(BaseModel):
    id: uuid.UUID
    patient_id: uuid.UUID
    label: str
    created_at: datetime
    last_used_at: datetime | None
    added_by_you: bool


class DeviceKeyCreatedOut(DeviceKeyOut):
    key: str = Field(
        description="Shown once. The device keeps it and sends it as X-Crisis-Key. Never logged."
    )


class DevicePressIn(BaseModel):
    """POST /crisis/device-press: the same as a signed-in press, minus the patient id."""

    model_config = ConfigDict(extra="forbid")

    client_event_id: uuid.UUID
    location: LocationIn | None = None
    triggered_at: AwareDatetime | None = None


class DevicePressOut(CrisisTriggerOut):
    patient_first_name: str


class DeviceEventOut(CrisisEventOut):
    patient_first_name: str
    nearby: FacilitiesOut


class AnonymousPressIn(BaseModel):
    """A press on a device with no key: nobody can be alerted, but it is logged for ops."""

    model_config = ConfigDict(extra="forbid")

    location: LocationIn | None = None


class AnonymousPressOut(SafetyNotice):
    logged: bool
